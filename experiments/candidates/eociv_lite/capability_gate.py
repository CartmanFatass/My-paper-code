def check_8_mutation_reaches_slot_and_policy_only() -> dict[str, object]:
    """A/B body mutation leaves W_minus/selection/tape/neutral identical while
    verifiably REACHING the receiver slot and the policy's first post-event
    input."""
    profile, episode_id, event_index = GATE_PROFILES[0], 1, 0
    states = (sib.SHOCK_A, sib.SHOCK_NONE, sib.SHOCK_A)
    states_b = (sib.SHOCK_B, sib.SHOCK_NONE, sib.SHOCK_A)
    runner_a = _boundary_runner(profile, episode_id, "LR", shock_states=states)
    runner_b = _boundary_runner(profile, episode_id, "LR", shock_states=states_b)
    runner_a.run_episode()
    runner_b.run_episode()
    rec_a = runner_a.boundary_records[0]
    rec_b = runner_b.boundary_records[0]
    # "Tape unreached by the body" is structural: the tape function's
    # signature admits only pre-outcome cluster identifiers, so the payload
    # body cannot be an input.  Assert the signature rather than calling the
    # same arguments twice (which would be vacuously equal).
    import inspect

    tape_signature_closed = set(
        inspect.signature(sib.control_tape_open).parameters
    ) == {"profile_registration_id", "episode_id", "event_index", "tape_seed"}
    boundary = sib.EVENT_TIMES[0]
    pre_identical = all(
        a == b for a, b in zip(runner_a.step_traces[:boundary], runner_b.step_traces[:boundary])
    )
    reaches_policy = (
        runner_a.step_traces[boundary].input_digest
        != runner_b.step_traces[boundary].input_digest
    )
    env_a2, env_b2 = _forced_pair(profile, episode_id, event_index)
    opp_a2 = env_a2.opportunity(event_index)
    opp_b2 = env_b2.opportunity(event_index)
    neutral_a = sib.actuate(
        "CS", opp_a2, env_a2.focal_payload(event_index), d_learned=False, d_control=False
    )
    neutral_b = sib.actuate(
        "CS", opp_b2, env_b2.focal_payload(event_index), d_learned=False, d_control=False
    )
    neutral_unreached = (
        neutral_a.slot == neutral_b.slot
        and neutral_a.body == neutral_b.body == sib.NEUTRAL_TOKEN
    )
    passed = (
        rec_a.slot != rec_b.slot                       # mutation reaches the slot
        and rec_a.w_minus == rec_b.w_minus             # sealed view unreached
        and rec_a.receipt.opportunity_identity == rec_b.receipt.opportunity_identity
        and tape_signature_closed
        and pre_identical
        and reaches_policy
        and neutral_unreached
    )
    return {"passed": bool(passed)}


def check_9_controls_execute_and_always_real_identity() -> dict[str, object]:
    """Pattern-only and knockout slots complete actual forward steps, and LR
    and CR produce byte-identical inputs, kernels, actions and recurrent
    writes under common noise."""
    profile, episode_id = GATE_PROFILES[0], 2
    pattern = _boundary_runner(profile, episode_id, "LR", body_override=sib.PATTERN_TOKEN)
    knockout = _boundary_runner(profile, episode_id, "LR", body_override=sib.knockout_payload_body())
    pattern.run_episode()
    knockout.run_episode()
    controls_ok = (
        len(pattern.step_traces) == len(knockout.step_traces) == roster_env.HORIZON
        and pattern.boundary_records[0].receipt.route == "REAL"
        and knockout.boundary_records[0].receipt.route == "REAL"
        and pattern.boundary_records[0].slot != knockout.boundary_records[0].slot
    )
    lr = _boundary_runner(profile, episode_id, "LR")
    cr = _boundary_runner(profile, episode_id, "CR")
    lr.run_episode()
    cr.run_episode()
    always_real_identical = lr.step_traces == cr.step_traces and (
        [r.receipt.slot_digest for r in lr.boundary_records]
        == [r.receipt.slot_digest for r in cr.boundary_records]
    )
    return {
        "passed": bool(controls_ok and always_real_identical),
        "lr_cr_byte_identical": bool(always_real_identical),
    }


def check_10_arm_support_and_registration() -> dict[str, object]:
    support: dict[tuple[str, str], int] = {}
    branch: dict[tuple[str, str, str], int] = {}
    for profile, episode_id, event_index, env, opportunity in _all_opportunities():
        arm = registered_arm(profile.name, episode_id, event_index)
        stratum = opportunity.cell_class
        support[(stratum, arm)] = support.get((stratum, arm), 0) + 1
        body = env.focal_payload(event_index)
        w_bytes = sib.w_minus(env.observe(), opportunity)
        actuation = sib.actuate(
            arm,
            opportunity,
            body,
            d_learned=registered_learned_decision(w_bytes),
            d_control=sib.control_tape_open(
                profile.name, episode_id, event_index, tape_seed=TAPE_SEED
            ),
        )
        key = (stratum, arm, actuation.route)
        branch[key] = branch.get(key, 0) + 1
    strata = sorted({stratum for stratum, _ in support})
    complete = all(
        support.get((stratum, arm), 0) > 0 for stratum in strata for arm in sib.ARMS
    )
    registration_ok = (
        REGISTERED_OUTCOME_EXPERIMENT["identity"]
        == "EOCIV-G32-SIBLING-4ARM-COMPLETE-BLOCK-D0"
        and REGISTERED_OUTCOME_EXPERIMENT["licensed"] is False
        and "NOT" in REGISTERED_OUTCOME_EXPERIMENT["outcome_design_is_not_gate_probes"]
        and "permutation tape" in REGISTERED_OUTCOME_EXPERIMENT["control_selector"]
    )
    return {
        "passed": bool(complete and strata and registration_ok),
        "support": {f"{stratum}/{arm}": count for (stratum, arm), count in sorted(support.items())},
        "routes": {
            f"{stratum}/{arm}/{route}": count
            for (stratum, arm, route), count in sorted(branch.items())
        },
        "registration_declares_gate_probes_not_outcome_design": registration_ok,
    }



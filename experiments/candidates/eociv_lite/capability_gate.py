def check_1_disabled_projection() -> dict[str, object]:
    """Disabled sibling == base G32: views (incl. critic_state), rewards,
    info, full outcome, and matching illegal-action rejection."""
    episodes = 0
    for profile in GATE_PROFILES:
        for episode_id in GATE_EPISODES:
            ledger = roster_env.make_ledger(
                episode_id, master_seed=MASTER_SEED, profile=profile
            )
            base = roster_env.RuntimeCapacityRosterEnv(ledger)
            disabled = sib.EocivSiblingRosterEnv(
                ledger, sibling_seed=SIBLING_SEED, intervention_enabled=False
            )
            for _ in range(roster_env.HORIZON):
                base_view = base.observe()
                sib_view = disabled.observe()
                if not (
                    base_view.time == sib_view.time
                    and np.array_equal(base_view.observations, sib_view.observations)
                    and np.array_equal(base_view.active_mask, sib_view.active_mask)
                    and np.array_equal(base_view.critic_state, sib_view.critic_state)
                    and base_view.load == sib_view.load
                    and base_view.target_mix == sib_view.target_mix
                    and base_view.membership_change == sib_view.membership_change
                ):
                    return {"passed": False, "detail": f"view drift ep={episode_id}"}
                actions = roster_env.constructive_actions(base_view)
                base_reward, base_done, base_info = base.step(actions)
                sib_reward, sib_done, sib_info = disabled.step(actions)
                if base_reward != sib_reward or base_done != sib_done or base_info != sib_info:
                    return {"passed": False, "detail": f"step drift ep={episode_id}"}
            base_outcome = base.outcome()
            disabled_outcome = disabled._base.outcome()
            if base_outcome != disabled_outcome:
                return {"passed": False, "detail": f"outcome drift ep={episode_id}"}
            if tuple(disabled.reward_trace) != base_outcome.reward_trace:
                return {"passed": False, "detail": f"trace drift ep={episode_id}"}
            episodes += 1
    # Matching rejection of representative illegal actions.
    ledger = roster_env.make_ledger(0, master_seed=MASTER_SEED, profile=GATE_PROFILES[0])
    base = roster_env.RuntimeCapacityRosterEnv(ledger)
    disabled = sib.EocivSiblingRosterEnv(
        ledger, sibling_seed=SIBLING_SEED, intervention_enabled=False
    )
    capacity = ledger.member_capacity
    illegal = []
    over = np.zeros((capacity, roster_env.ACTION_DIM), dtype=np.float32)
    over[0, 0] = np.float32(1.5)
    illegal.append(over)
    inactive = np.zeros((capacity, roster_env.ACTION_DIM), dtype=np.float32)
    inactive[ledger.initial_keys[-1] + 1 if ledger.initial_keys[-1] + 1 < capacity else 0, 0] = (
        np.float32(0.5) if ledger.initial_keys[-1] + 1 < capacity else np.float32(1.5)
    )
    illegal.append(inactive)
    nonfinite = np.zeros((capacity, roster_env.ACTION_DIM), dtype=np.float32)
    nonfinite[0, 0] = np.float32("nan")
    illegal.append(nonfinite)
    rejection_parity = True
    for actions in illegal:
        base_raised = sib_raised = False
        try:
            roster_env.RuntimeCapacityRosterEnv(ledger).step(actions)
        except ValueError:
            base_raised = True
        try:
            sib.EocivSiblingRosterEnv(
                ledger, sibling_seed=SIBLING_SEED, intervention_enabled=False
            ).step(actions)
        except ValueError:
            sib_raised = True
        if base_raised != sib_raised or not base_raised:
            rejection_parity = False
    return {
        "passed": bool(episodes == 24 and rejection_parity),
        "episodes_compared": episodes,
        "illegal_action_rejection_parity": rejection_parity,
    }



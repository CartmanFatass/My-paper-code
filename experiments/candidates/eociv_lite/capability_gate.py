@dataclass(frozen=True)
class StepGeometry:
    """Exact per-step reward geometry for the focal receiver.

    LOAD-BEARING BASELINE ASSUMPTION: every non-focal active member plays the
    blind-constructive action (effort = published load, mix = published mix —
    the base environment's exact optimum family).  The channel terms below
    encode that baseline, and ``_envelopes_for_state`` drives the real
    environment with ``constructive_actions`` for the non-focal members for
    exactly that reason: the oracle's informed/blind values and the executed
    conformance run must share one baseline, or the correspondence silently
    breaks.  Change one only with the other.
    """

    load: Fraction
    mix: Fraction
    receiver_caps: tuple[Fraction, Fraction]
    aggregate: tuple[Fraction, Fraction]

    def channel_terms(self, state: str) -> tuple[Fraction, Fraction, Fraction, Fraction]:
        """(k1, x_star, k2, y_star) for R = clip(1 - (k1|x-x*| + k2|y-y*|)/2)."""
        c = sib.SHOCK_COEFF[state]
        l, m = self.load, self.mix
        c1, c2 = self.receiver_caps
        a1, a2 = self.aggregate
        t1 = c * l * m * a1
        t2 = c * l * (1 - m) * a2
        k1 = c1 / t1
        k2 = c2 / t2
        x_star = l * m * (a1 * (c - 1) + c1) / c1
        y_star = l * (1 - m) * (a2 * (c - 1) + c2) / c2
        return k1, x_star, k2, y_star

    def reward(self, state: str, x: Fraction, y: Fraction) -> Fraction:
        k1, x_star, k2, y_star = self.channel_terms(state)
        value = 1 - (k1 * abs(x - x_star) + k2 * abs(y - y_star)) / 2
        if value < 0:
            return Fraction(0)
        if value > 1:
            return Fraction(1)
        return value


def _candidate_points(geometry: StepGeometry, states: tuple[str, ...]) -> list[tuple[Fraction, Fraction]]:
    """All vertices of the joint piecewise-linear arrangement inside T."""
    lines: list[tuple[Fraction, Fraction, Fraction]] = [
        (Fraction(1), Fraction(0), Fraction(0)),   # x = 0
        (Fraction(0), Fraction(1), Fraction(0)),   # y = 0
        (Fraction(1), Fraction(1), Fraction(1)),   # x + y = 1
    ]
    for state in states:
        k1, x_star, k2, y_star = geometry.channel_terms(state)
        lines.append((Fraction(1), Fraction(0), x_star))   # channel-1 match
        lines.append((Fraction(0), Fraction(1), y_star))   # channel-2 match
        for sx in (1, -1):
            for sy in (1, -1):
                # clip-0 boundary: sx*k1*(x-x*) + sy*k2*(y-y*) = 2
                lines.append(
                    (sx * k1, sy * k2, 2 + sx * k1 * x_star + sy * k2 * y_star)
                )
    points: set[tuple[Fraction, Fraction]] = {
        (Fraction(0), Fraction(0)), (Fraction(1), Fraction(0)), (Fraction(0), Fraction(1)),
    }
    for i in range(len(lines)):
        a1, b1, c1 = lines[i]
        for j in range(i + 1, len(lines)):
            a2, b2, c2 = lines[j]
            det = a1 * b2 - a2 * b1
            if det == 0:
                continue
            x = (c1 * b2 - c2 * b1) / det
            y = (a1 * c2 - a2 * c1) / det
            if x >= 0 and y >= 0 and x + y <= 1:
                points.add((x, y))
    return sorted(points)


@dataclass(frozen=True)
class FullSupportOracle:
    """Exact full-support oracle valuations for one focal cell."""

    event_index: int
    receiver_key: int
    informed_value: Fraction
    blind_value: Fraction
    reveal_value: Fraction
    optimal_sets_disjoint_every_step: bool
    per_step_optima: dict[str, tuple[tuple[Fraction, Fraction], ...]]


def full_support_oracle(ledger, event_index: int, receiver_key: int) -> FullSupportOracle:
    cell_class = sib.CELL_CLASS[event_index]
    states = CRITICAL_STATES if cell_class == "CRITICAL" else (sib.SHOCK_NONE,)
    prior = (
        {state: sib.CRITICAL_PRIOR[state] for state in states}
        if cell_class == "CRITICAL"
        else {sib.SHOCK_NONE: Fraction(1)}
    )
    keys = _active_keys_in_segment(ledger, event_index)
    if receiver_key not in keys:
        raise ValueError("oracle receiver is not active in the segment")
    receiver_caps = (
        _frac(ledger.capabilities[receiver_key, 0]),
        _frac(ledger.capabilities[receiver_key, 1]),
    )
    aggregate = (
        sum((_frac(ledger.capabilities[key, 0]) for key in keys), Fraction(0)),
        sum((_frac(ledger.capabilities[key, 1]) for key in keys), Fraction(0)),
    )
    start = sib.EVENT_TIMES[event_index]

    informed_value = Fraction(0)
    blind_value = Fraction(0)
    disjoint_every_step = True
    per_step_optima: dict[str, list[tuple[Fraction, Fraction]]] = {s: [] for s in states}

    for time in range(start, start + sib.SEGMENT_LENGTH):
        geometry = StepGeometry(
            load=_frac(ledger.load[time]), mix=_frac(ledger.target_mix[time]),
            receiver_caps=receiver_caps, aggregate=aggregate,
        )
        candidates = _candidate_points(geometry, states)
        maxima: dict[str, Fraction] = {}
        argmax_first: dict[str, tuple[Fraction, Fraction]] = {}
        for state in states:
            best = None
            best_point = None
            for point in candidates:
                value = geometry.reward(state, *point)
                if best is None or value > best:
                    best, best_point = value, point
            maxima[state] = best
            argmax_first[state] = best_point
            per_step_optima[state].append(best_point)
            informed_value += prior[state] * best
        blind_best = None
        for point in candidates:
            value = sum(
                (prior[state] * geometry.reward(state, *point) for state in states),
                Fraction(0),
            )
            if blind_best is None or value > blind_best:
                blind_best = value
        blind_value += blind_best
        if len(states) == 2:
            # Disjointness of the FULL optimal sets, certified over the joint
            # arrangement: the A-optimal set is a union of faces whose
            # vertices are all in `candidates`, so the max of R_B over it is
            # attained at a candidate with R_A == maxA.
            a, b = states
            cross_b = max(
                (
                    geometry.reward(b, *point)
                    for point in candidates
                    if geometry.reward(a, *point) == maxima[a]
                ),
            )
            cross_a = max(
                (
                    geometry.reward(a, *point)
                    for point in candidates
                    if geometry.reward(b, *point) == maxima[b]
                ),
            )
            if not (cross_b < maxima[b] and cross_a < maxima[a]):
                disjoint_every_step = False

    return FullSupportOracle(
        event_index=event_index,
        receiver_key=receiver_key,
        informed_value=informed_value,
        blind_value=blind_value,
        reveal_value=informed_value - blind_value,
        optimal_sets_disjoint_every_step=disjoint_every_step,
        per_step_optima={s: tuple(v) for s, v in per_step_optima.items()},
    )


def _quantized_action(point: tuple[Fraction, Fraction], mix: Fraction) -> tuple[np.float32, np.float32]:
    """The nearest executed float32 action for an exact (x, y) optimum."""
    x, y = point
    effort = x + y
    mu = (x / effort) if effort > 0 else mix
    return np.float32(2.0 * float(effort) - 1.0), np.float32(2.0 * float(mu) - 1.0)


def _quantized_reward(
    geometry: StepGeometry, state: str, a0: np.float32, a1: np.float32
) -> Fraction:
    """Exact reward of the quantized float32 action, lifted losslessly."""
    effort = (Fraction(float(a0)) + 1) / 2
    mu = (Fraction(float(a1)) + 1) / 2
    return geometry.reward(state, effort * mu, effort * (1 - mu))


